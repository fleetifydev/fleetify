// The app's commands (`APP_COMMANDS`) and the check against lib.rs, shared
// with the crate's tests.
include!("src/app_commands.rs");

fn main() {
    // Every command lib.rs registers must be in the manifest: one that isn't
    // is refused at runtime, and the test that says so doesn't block a
    // merge. Checked here, so a mismatch fails the build. Including lib.rs
    // makes Cargo rebuild and rerun this script whenever it changes.
    let registered =
        registered_commands(include_str!("src/lib.rs")).unwrap_or_else(|error| panic!("{error}"));
    if let Some(drift) = manifest_drift(&registered) {
        panic!("{drift}");
    }

    // The app's ACL manifest. tauri-build generates an `allow-*` and a
    // `deny-*` permission for every app command, in
    // `permissions/autogenerated/` (rewritten on every build, not committed).
    // `capabilities/default.json` grants them to the main webview through
    // the `app-commands` set (`permissions/app-commands.toml`), and setup
    // grants the same to the app's own origin. Without a manifest, app
    // commands have no permissions to grant, and Tauri refuses them from any
    // remote origin: the release UI, which the embedded backend serves on
    // `http://127.0.0.1:<port>`, is one.
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .app_manifest(tauri_build::AppManifest::new().commands(APP_COMMANDS)),
    )
    .expect("failed to run tauri-build");
}
