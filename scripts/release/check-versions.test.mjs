/**
 * Tests for check-versions.mjs, which checks that every file holding
 * Fleetify's version holds the same one: the files release-please bumps
 * together in a release pull request.
 *
 *   node --test scripts/release/check-versions.test.mjs
 *
 * The fixture trees, made in a temp folder, hold a workspace of two crates,
 * fleetify-core (crates/fleetify-core) and fleetify-app (src-tauri), with each
 * file a release bumps.
 */
import { after, describe, test } from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { readVersions, versionProblems, workspaceMembers } from "./check-versions.mjs";

const SCRIPT = fileURLToPath(new URL("./check-versions.mjs", import.meta.url));
const REPO = fileURLToPath(new URL("../../", import.meta.url));

/** The workspace's crates, in the order Cargo.toml lists their folders. */
const CRATES = [
  "browser-mcp",
  "dispatch-mcp",
  "fleet-wipe",
  "fleetify-core",
  "fleetify-backend",
  "memory-mcp",
  "reveng-mcp",
  "fleetify-app",
];

const TMP = mkdtempSync(join(tmpdir(), "check-versions-"));
after(() => rmSync(TMP, { recursive: true, force: true }));
let trees = 0;

const V = "1.2.3";

const CARGO_TOML = `# The workspace: the app and one crate.
[workspace]
resolver = "2"
members = [
  "crates/fleetify-core", # the shared types
  # the shell
  "src-tauri",
]

[workspace.package]
version = "@workspace@" # release-please bumps this
edition = "2021"

[workspace.dependencies]
fleetify-core = { path = "crates/fleetify-core" }
serde = { version = "1.0.228", features = ["derive"] }

[patch.crates-io]
tauri-runtime-wry = { path = "vendor/tauri-runtime-wry" }
`;

const CORE_TOML = `[package]
name = 'fleetify-core'
version.workspace = true
edition.workspace = true

[dependencies]
serde.workspace = true
`;

const APP_TOML = `[package]
description = """
The shell. # not a comment
[not-a-table]
name = "not-its-name"
"""
name = "fleetify-app"
version = { workspace = true }
edition.workspace = true

[target.'cfg(target_os = "linux")'.dependencies]
gtk = "0.18"
`;

/** A Cargo.lock entry for `name` at `version`, or nothing when the version is null. */
const lockEntry = (name, version, rest = "") =>
  version === null ? "" : `\n[[package]]\nname = "${name}"\nversion = "${version}"\n${rest}`;

/**
 * The files of a fixture tree, each source at V unless named: npm
 * (package.json), lock and lockRoot (package-lock.json's version and
 * packages[""].version), workspace (Cargo.toml), tauri (tauri.conf.json), core
 * and app (their Cargo.lock entries; null leaves the entry out) and manifest
 * (.release-please-manifest.json).
 */
function files({ npm = V, lock = V, lockRoot = V, workspace = V, tauri = V, core = V, app = V, manifest = V } = {}) {
  const json = (value) => `${JSON.stringify(value, null, 2)}\n`;
  return {
    "package.json": json({ name: "fleetify", private: true, version: npm }),
    "package-lock.json": json({
      name: "fleetify",
      version: lock,
      lockfileVersion: 3,
      requires: true,
      packages: { "": { name: "fleetify", version: lockRoot }, "node_modules/react": { version: "19.2.0" } },
    }),
    "Cargo.toml": CARGO_TOML.replace("@workspace@", workspace),
    "crates/fleetify-core/Cargo.toml": CORE_TOML,
    "src-tauri/Cargo.toml": APP_TOML,
    "src-tauri/tauri.conf.json": json({ productName: "Fleetify", version: tauri, identifier: "com.fleetify.app" }),
    "Cargo.lock": [
      "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n",
      lockEntry("fleetify-app", app, 'dependencies = [\n "fleetify-core",\n "serde",\n]\n'),
      lockEntry("fleetify-core", core, 'dependencies = [\n "serde",\n]\n'),
      // A crate from crates.io and a patched one, neither a workspace crate.
      lockEntry("serde", "1.0.228", 'source = "registry+https://github.com/rust-lang/crates.io-index"\nchecksum = "9a8e94ea7f378bd32cbbd37198a4a91436180c5bb472411e48b5ec2e2124ae9e"\n'),
      lockEntry("tauri-runtime-wry", "2.11.2", 'dependencies = [\n "serde",\n]\n'),
    ].join(""),
    ".release-please-manifest.json": json({ ".": manifest }),
  };
}

/** A fixture tree holding `contents` (path → text; undefined leaves the file out). */
function tree(contents = files()) {
  const root = join(TMP, `tree-${(trees += 1)}`);
  for (const [rel, text] of Object.entries(contents)) {
    if (text === undefined) continue;
    mkdirSync(dirname(join(root, rel)), { recursive: true });
    writeFileSync(join(root, rel), text);
  }
  return root;
}

/** The sources of a fixture tree, each with `versions[i]`. */
const sources = (...versions) =>
  [
    "package.json",
    "package-lock.json",
    'package-lock.json packages[""]',
    "Cargo.toml [workspace.package]",
    "src-tauri/tauri.conf.json",
    "Cargo.lock fleetify-core",
    "Cargo.lock fleetify-app",
    '.release-please-manifest.json "."',
  ].map((source, i) => ({ source, version: versions[i] }));

describe("workspaceMembers", () => {
  /** A reader of the fixture crates' manifests, by folder. */
  const manifests = (overrides = {}) => {
    const all = { "crates/fleetify-core": CORE_TOML, "src-tauri": APP_TOML, ...overrides };
    return (member) => {
      assert.ok(Object.hasOwn(all, member), `asked for ${member}`);
      return all[member];
    };
  };

  test("the crates' names, in the order of members, each from its own Cargo.toml", () => {
    assert.deepEqual(workspaceMembers(files()["Cargo.toml"], manifests()), ["fleetify-core", "fleetify-app"]);
  });

  test("the repository's eight crates", () => {
    const text = (rel) => readFileSync(join(REPO, rel), "utf8");
    assert.deepEqual(workspaceMembers(text("Cargo.toml"), (member) => text(`${member}/Cargo.toml`)), CRATES);
  });

  test("a glob in members is refused: release-please-config.json names each crate", () => {
    const cargoToml = files()["Cargo.toml"].replace('"crates/fleetify-core", # the shared types', '"crates/*",');
    assert.throws(() => workspaceMembers(cargoToml, manifests()), /crates\/\*.*glob/);
  });

  test("a crate that doesn't take the workspace's version is refused: release-please bumps only that one", () => {
    for (const version of ['version = "1.2.3"', 'version = "1.2.3" # in step, for now', ""]) {
      const core = CORE_TOML.replace("version.workspace = true", version);
      assert.throws(
        () => workspaceMembers(files()["Cargo.toml"], manifests({ "crates/fleetify-core": core })),
        /crates\/fleetify-core\/Cargo\.toml.*workspace's version/,
        JSON.stringify(version),
      );
    }
  });

  test("a crate without a name, or a Cargo.toml without members, is refused", () => {
    const core = CORE_TOML.replace("name = 'fleetify-core'\n", "");
    assert.throws(
      () => workspaceMembers(files()["Cargo.toml"], manifests({ "crates/fleetify-core": core })),
      /crates\/fleetify-core\/Cargo\.toml has no \[package\] name/,
    );
    const noMembers = files()["Cargo.toml"].replace(/members = \[[^\]]*\]\n/, "");
    assert.throws(() => workspaceMembers(noMembers, manifests()), /no \[workspace\] members/);
  });
});

describe("readVersions", () => {
  test("each source's own version, read from its own place", () => {
    const root = tree(
      files({ npm: "1.0.1", lock: "1.0.2", lockRoot: "1.0.3", workspace: "1.0.4", tauri: "1.0.5", core: "1.0.6", app: "1.0.7", manifest: "1.0.8" }),
    );
    assert.deepEqual(readVersions(root), sources("1.0.1", "1.0.2", "1.0.3", "1.0.4", "1.0.5", "1.0.6", "1.0.7", "1.0.8"));
  });

  test("CRLF line endings, as a Windows checkout may have, read the same", () => {
    const crlf = Object.fromEntries(Object.entries(files()).map(([rel, text]) => [rel, text.replace(/\n/g, "\r\n")]));
    assert.deepEqual(readVersions(tree(crlf)), sources(V, V, V, V, V, V, V, V));
  });

  test("a crate missing from Cargo.lock has no version", () => {
    assert.deepEqual(readVersions(tree(files({ core: null }))), sources(V, V, V, V, V, undefined, V, V));
  });

  test("a crates.io crate named like a workspace crate is a source of its own, as release-please would bump it too", () => {
    const contents = files();
    contents["Cargo.lock"] += lockEntry("fleetify-core", "0.3.0", 'source = "registry+https://github.com/rust-lang/crates.io-index"\n');
    const found = readVersions(tree(contents)).filter(({ source }) => source === "Cargo.lock fleetify-core");
    assert.deepEqual(found.map(({ version }) => version), [V, "0.3.0"]);
  });

  test("an unused patch named like a workspace crate isn't a source: release-please's jsonpath reads [[package]] alone", () => {
    const contents = files();
    contents["Cargo.lock"] += '\n[[patch.unused]]\nname = "fleetify-core"\nversion = "0.0.1"\n';
    assert.deepEqual(readVersions(tree(contents)), sources(V, V, V, V, V, V, V, V));
  });

  test("a file that is missing or can't be parsed is an error that names it", () => {
    assert.throws(() => readVersions(tree({ ...files(), "Cargo.lock": undefined })), /Cargo\.lock/);
    assert.throws(() => readVersions(tree({ ...files(), "src-tauri/tauri.conf.json": "{" })), /src-tauri\/tauri\.conf\.json/);
    assert.throws(() => readVersions(tree({ ...files(), "Cargo.lock": 'name = "unclosed\n' })), /Cargo\.lock/);
  });
});

describe("versionProblems", () => {
  test("every source at one version: no problems", () => {
    assert.deepEqual(versionProblems(readVersions(tree())), []);
  });

  test("one crate off: one problem, naming its Cargo.lock entry", () => {
    assert.deepEqual(versionProblems(readVersions(tree(files({ core: "1.2.4" })))), ["Cargo.lock fleetify-core: 1.2.4"]);
  });

  test("package.json off: it alone is listed, though it comes first", () => {
    assert.deepEqual(versionProblems(readVersions(tree(files({ npm: "1.3.0" })))), ["package.json: 1.3.0"]);
  });

  test("each source that differs from the version most sources hold is listed, and a missing one too", () => {
    const entries = sources("2.0.0", "2.0.0", "1.9.0", "2.0.0", "2.0.0", undefined, "2.0.0", "2.1.0");
    assert.deepEqual(versionProblems(entries), [
      'package-lock.json packages[""]: 1.9.0',
      "Cargo.lock fleetify-core: missing",
      '.release-please-manifest.json ".": 2.1.0',
    ]);
  });

  test("on a tie, the version the first sources hold is taken as the right one", () => {
    assert.deepEqual(
      versionProblems([
        { source: "a", version: "1.0.0" },
        { source: "b", version: "2.0.0" },
      ]),
      ["b: 2.0.0"],
    );
  });

  test("no source with a version: each is listed", () => {
    assert.deepEqual(versionProblems([{ source: "a", version: undefined }, { source: "b", version: undefined }]), [
      "a: missing",
      "b: missing",
    ]);
  });
});

describe("the repository", () => {
  test("14 sources, all at package.json's version", () => {
    const entries = readVersions(REPO);
    const { version } = JSON.parse(readFileSync(join(REPO, "package.json"), "utf8"));
    assert.deepEqual(
      entries.map(({ source }) => source),
      [
        "package.json",
        "package-lock.json",
        'package-lock.json packages[""]',
        "Cargo.toml [workspace.package]",
        "src-tauri/tauri.conf.json",
        ...CRATES.map((crate) => `Cargo.lock ${crate}`),
        '.release-please-manifest.json "."',
      ],
    );
    assert.equal(entries.length, 14);
    assert.deepEqual(versionProblems(entries), []);
    assert.deepEqual([...new Set(entries.map((entry) => entry.version))], [version]);
  });
});

describe("check-versions CLI", () => {
  /** Run the CLI with `args`, from a folder outside the repository. */
  const cli = (args) => spawnSync(process.execPath, [SCRIPT, ...args], { encoding: "utf8", cwd: TMP });

  test("the repository, from any folder: exit 0 and one line", () => {
    const { version } = JSON.parse(readFileSync(join(REPO, "package.json"), "utf8"));
    const run = cli([]);
    assert.equal(run.stderr, "");
    assert.equal(run.status, 0);
    assert.equal(run.stdout, `versions: all ${version} (14 sources)\n`);
  });

  test("a tree whose sources agree: exit 0 with its count", () => {
    const run = cli(["--root", tree()]);
    assert.equal(run.status, 0, run.stderr);
    assert.equal(run.stdout, `versions: all ${V} (8 sources)\n`);
  });

  test("a tree whose sources disagree: exit 1, each differing source on a line of its own", () => {
    const run = cli(["--root", tree(files({ core: "1.2.4", manifest: "1.2.2" }))]);
    assert.equal(run.status, 1);
    assert.equal(run.stdout, "");
    const lines = run.stderr.split("\n");
    assert.ok(lines.includes("Cargo.lock fleetify-core: 1.2.4"), run.stderr);
    assert.ok(lines.includes('.release-please-manifest.json ".": 1.2.2'), run.stderr);
    assert.equal(lines.filter((line) => /: \d+\.\d+\.\d+$/.test(line)).length, 2, run.stderr);
  });

  test("a tree with a file missing: exit 1, naming it", () => {
    const run = cli(["--root", tree({ ...files(), "package-lock.json": undefined })]);
    assert.equal(run.status, 1);
    assert.match(run.stderr, /package-lock\.json/);
  });

  test("an unknown argument, or --root without a folder: exit 2 with the usage", () => {
    for (const args of [["--bogus"], ["--root"], ["--root", ""], ["--root", tree(), "extra"]]) {
      const run = cli(args);
      assert.equal(run.status, 2, JSON.stringify(args));
      assert.match(run.stderr, /usage: node scripts\/release\/check-versions\.mjs/, JSON.stringify(args));
    }
  });
});
